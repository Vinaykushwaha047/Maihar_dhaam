const translationMap = new Map(
  Object.entries(hindiTranslations).map(([english, hindi]) => [
    english.trim().replace(/\s+/g, " "),
    hindi
  ])
);
const englishTranslations = new Map([
  ["जय माँ शारदा", "Hail Maa Sharda."],
  ["मैहर नगरी में आपका स्वागत है।", "Welcome to the city of Maihar."],
  ["जय माता दी", "Hail the Mother Goddess."],
  ["श्रद्धा और विश्वास", "Devotion and faith"]
]);
const reverseTranslationMap = new Map(
  [...translationMap].map(([english, hindi]) => [hindi, english])
);
const languageControl = document.querySelector("#site-language");
const languageLabel = document.querySelector("#language-label");
const normalizeTranslationText = (text) => text.trim().replace(/\s+/g, " ");
const originalDocumentTitle = document.title;
const originalDescription = document.querySelector('meta[name="description"]')?.content;
const originalText = new WeakMap();
const originalAttributes = new WeakMap();

function translateTextNode(node, language) {
  if (!originalText.has(node)) originalText.set(node, node.nodeValue);
  const source = originalText.get(node);
  const normalized = normalizeTranslationText(source);
  const translated = language === "hi"
    ? translationMap.get(normalized) ?? normalized
    : englishTranslations.get(normalized) ?? reverseTranslationMap.get(normalized) ?? normalized;

  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const value = `${leading}${translated}${trailing}`;
  if (node.nodeValue !== value) node.nodeValue = value;
}

function translateElementAttributes(element, language) {
  const attributes = ["alt", "aria-label", "data-image-alt", "placeholder", "title"];
  if (!originalAttributes.has(element)) originalAttributes.set(element, {});
  const originals = originalAttributes.get(element);

  attributes.forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;
    const current = element.getAttribute(attribute);
    if (!current.trim()) return;
    if (!(attribute in originals)) originals[attribute] = element.getAttribute(attribute);

    const source = originals[attribute];
    const normalized = normalizeTranslationText(source);
    const translated = language === "hi"
      ? translationMap.get(normalized) ?? normalized
      : englishTranslations.get(normalized) ?? reverseTranslationMap.get(normalized) ?? normalized;
    element.setAttribute(attribute, translated);
  });
}

function translatePage(language) {
  document.documentElement.lang = language;
  if (language === "hi") {
    const sourceTitle = originalDocumentTitle;
    document.title = translationMap.get(sourceTitle) ?? sourceTitle;
  } else {
    document.title = originalDocumentTitle;
  }
  const description = document.querySelector('meta[name="description"]');
  if (description && originalDescription) {
    description.content = language === "hi"
      ? (translationMap.get(originalDescription) ?? originalDescription)
      : originalDescription;
  }

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) translateTextNode(node, language);

  document.querySelectorAll("*").forEach((element) => translateElementAttributes(element, language));
  if (languageControl) languageControl.setAttribute("aria-label", language === "hi" ? "भाषा चुनें" : "Choose language");
  if (languageLabel) languageLabel.textContent = language === "hi" ? "भाषा" : "Language";
}

if (languageControl) {
  let savedLanguage = "en";
  try {
    savedLanguage = localStorage.getItem("ma-sharda-language") === "hi" ? "hi" : "en";
  } catch (error) {
    console.warn("Could not read the saved language preference.", error);
  }

  languageControl.value = savedLanguage;
  translatePage(savedLanguage);
  languageControl.addEventListener("change", () => {
    const language = languageControl.value === "hi" ? "hi" : "en";
    translatePage(language);
    try {
      localStorage.setItem("ma-sharda-language", language);
    } catch (error) {
      console.warn("Could not save the language preference.", error);
    }
  });

  const translationObserver = new MutationObserver((mutations) => {
    const language = languageControl.value;
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((addedNode) => {
        if (addedNode.nodeType === Node.TEXT_NODE) {
          translateTextNode(addedNode, language);
        } else if (addedNode.nodeType === Node.ELEMENT_NODE) {
          const walker = document.createTreeWalker(addedNode, NodeFilter.SHOW_TEXT);
          let textNode;
          while ((textNode = walker.nextNode())) translateTextNode(textNode, language);
          translateElementAttributes(addedNode, language);
          addedNode.querySelectorAll("*").forEach((element) => translateElementAttributes(element, language));
        }
      });
    });
  });
  translationObserver.observe(document.body, { childList: true, subtree: true });
}
